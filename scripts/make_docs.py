"""Regenerate SAMPLE_QA.md and SOURCES.md from the live assistant and sources.csv.

python -m scripts.make_docs
"""
import csv
from pathlib import Path

from rag.assistant import Assistant

ROOT = Path(__file__).resolve().parent.parent

QUESTIONS = [
    "What is the expense ratio of Parag Parikh Flexi Cap Fund?",
    "What is the exit load of Parag Parikh Flexi Cap Fund?",
    "ELSS lock-in?",
    "What is the minimum SIP for Parag Parikh ELSS Tax Saver Fund?",
    "What is the riskometer and benchmark of Parag Parikh Large Cap Fund?",
    "What is the exit load of Parag Parikh Liquid Fund?",
    "How do I download my capital-gains statement?",
    "Should I buy Parag Parikh Flexi Cap Fund now?",
    "What were the 5-year returns of the ELSS fund?",
    "My PAN is ABCDE1234F, can you check my folio?",
]


def main():
    bot = Assistant()
    out = ["# Sample Q&A", "",
           "Generated by `python -m scripts.make_docs` — these are the assistant's real outputs "
           "(extractive mode, no LLM key). Includes 7 factual answers and 3 guardrail cases.", ""]
    for i, q in enumerate(QUESTIONS, 1):
        r = bot.ask(q)
        out += [f"### {i}. {q}", f"*Type: {r.kind}*", "", r.as_markdown(), "", "---", ""]
    (ROOT / "SAMPLE_QA.md").write_text("\n".join(out), encoding="utf-8")

    rows = list(csv.DictReader(open(ROOT / "data/sources.csv", encoding="utf-8")))
    src = ["# Source list", "",
           f"{len(rows)} official public pages — PPFAS AMC, AMFI and SEBI only. No third-party blogs. "
           "Machine-readable copy: `data/sources.csv`.", "",
           "| # | Publisher | Page | Type | Scheme |", "|---|---|---|---|---|"]
    for r in rows:
        src.append(f"| {r['id']} | {r['publisher']} | [{r['title']}]({r['url']}) | {r['type']} | {r['scheme']} |")
    (ROOT / "SOURCES.md").write_text("\n".join(src) + "\n", encoding="utf-8")
    # README = hand-written head + the generated source list, sample Q&A and disclaimer
    def body(name):
        lines = (ROOT / name).read_text(encoding="utf-8").splitlines()
        return "\n".join("#" + l if l.startswith("#") else l for l in lines)  # demote headings one level
    readme = "\n\n".join([(ROOT / "docs/README_head.md").read_text(encoding="utf-8").rstrip(),
                           body("SOURCES.md"), body("SAMPLE_QA.md"), body("DISCLAIMER.md")])
    (ROOT / "README.md").write_text(readme + "\n", encoding="utf-8")
    print("wrote SAMPLE_QA.md, SOURCES.md and README.md")


if __name__ == "__main__":
    main()
